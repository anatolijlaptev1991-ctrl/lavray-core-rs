//! RFC 8448 §3: сверка key schedule с официальными векторами.

#[cfg(test)]
mod rfc {
    use lavray_engine::reality::kdf::Schedule;

    /// RFC 8448 §3 (Simple 1-RTT Handshake): handshake traffic secrets.
    #[test]
    fn rfc8448_handshake_secrets() {
        let ikm_ecdhe: [u8; 32] = [
            0x8b, 0xd4, 0x05, 0x4f, 0xb5, 0x5b, 0x9d, 0x63, 0xfd, 0xfb, 0xac, 0xf9, 0xf0, 0x4b,
            0x9f, 0x0d, 0x35, 0xe6, 0xd6, 0x3f, 0x53, 0x75, 0x63, 0xef, 0xd4, 0x62, 0x72, 0x90,
            0x0f, 0x89, 0x49, 0x2d,
        ];
        let th: [u8; 32] = [
            0x86, 0x0c, 0x06, 0xed, 0xc0, 0x78, 0x58, 0xee, 0x8e, 0x78, 0xf0, 0xe7, 0x42, 0x8c,
            0x58, 0xed, 0xd6, 0xb4, 0x3f, 0x2c, 0xa3, 0xe6, 0xe9, 0x5f, 0x02, 0xed, 0x06, 0x3c,
            0xf0, 0xe1, 0xca, 0xd8,
        ];
        let sched = Schedule::new(&ikm_ecdhe, &th);
        let want_c: [u8; 32] = [
            0xb3, 0xed, 0xdb, 0x12, 0x6e, 0x06, 0x7f, 0x35, 0xa7, 0x80, 0xb3, 0xab, 0xf4, 0x5e,
            0x2d, 0x8f, 0x3b, 0x1a, 0x95, 0x07, 0x38, 0xf5, 0x2e, 0x96, 0x00, 0x74, 0x6a, 0x0e,
            0x27, 0xa5, 0x5a, 0x21,
        ];
        let want_s: [u8; 32] = [
            0xb6, 0x7b, 0x7d, 0x69, 0x0c, 0xc1, 0x6c, 0x4e, 0x75, 0xe5, 0x42, 0x13, 0xcb, 0x2d,
            0x37, 0xb4, 0xe9, 0xc9, 0x12, 0xbc, 0xde, 0xd9, 0x10, 0x5d, 0x42, 0xbe, 0xfd, 0x59,
            0xd3, 0x91, 0xad, 0x38,
        ];
        assert_eq!(sched.client_hs, want_c, "c hs traffic");
        assert_eq!(sched.server_hs, want_s, "s hs traffic");
    }

    /// RFC 8448 §3: application secrets по транскрипту §4-шага (тот же
    /// TH + server/client Finished; здесь проверяем цепочку derive_app).
    /// RFC 8448 §3: ap-секреты по транскрипту CH…SF‖CF.
    #[test]
    fn rfc8448_application_secrets() {
        // RFC 8448 §3: ap traffic по ПОЛНОМУ транскрипту (CH…SF‖CF),
        // hash = 9608102a… (константа ниже — контрольная сверка).
        let msgs: serde_json::Value =
            serde_json::from_str(include_str!("rfc8448_msgs.json")).expect("json");
        // ap-секреты: транскрипт = CH‖SH‖server-record(EE+Cert+CV+SF),
        // БЕЗ client Finished (RFC §3: hash = 9608102a…; подтверждено
        // ключлогом openssl: SERVER_TRAFFIC_SECRET_0 = 2759c243…)
        let keys = ["ch", "sh", "payload"];
        let parts: Vec<Vec<u8>> = keys
            .iter()
            .map(|k| {
                let hex = msgs[*k].as_str().expect("hex");
                (0..hex.len())
                    .step_by(2)
                    .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).expect("hex byte"))
                    .collect()
            })
            .collect();
        let refs: Vec<&[u8]> = parts.iter().map(Vec::as_slice).collect();
        let th_ap = lavray_engine::reality::kdf::transcript_hash(&refs);
        let expect_th: [u8; 32] = [
            0x96, 0x08, 0x10, 0x2a, 0x0f, 0x1c, 0xcc, 0x6d, 0xb6, 0x25, 0x0b, 0x7b, 0x7e, 0x41,
            0x7b, 0x1a, 0x00, 0x0e, 0xaa, 0xda, 0x3d, 0xaa, 0xe4, 0x77, 0x7a, 0x76, 0x86, 0xc9,
            0xff, 0x83, 0xdf, 0x13,
        ];
        assert_eq!(th_ap, expect_th, "hash(CH…SF‖CF) из RFC §3");

        let ikm_ecdhe: [u8; 32] = [
            0x8b, 0xd4, 0x05, 0x4f, 0xb5, 0x5b, 0x9d, 0x63, 0xfd, 0xfb, 0xac, 0xf9, 0xf0, 0x4b,
            0x9f, 0x0d, 0x35, 0xe6, 0xd6, 0x3f, 0x53, 0x75, 0x63, 0xef, 0xd4, 0x62, 0x72, 0x90,
            0x0f, 0x89, 0x49, 0x2d,
        ];
        let th_hs: [u8; 32] = [
            0x86, 0x0c, 0x06, 0xed, 0xc0, 0x78, 0x58, 0xee, 0x8e, 0x78, 0xf0, 0xe7, 0x42, 0x8c,
            0x58, 0xed, 0xd6, 0xb4, 0x3f, 0x2c, 0xa3, 0xe6, 0xe9, 0x5f, 0x02, 0xed, 0x06, 0x3c,
            0xf0, 0xe1, 0xca, 0xd8,
        ];
        let mut sched = Schedule::new(&ikm_ecdhe, &th_hs);
        let th_ap = lavray_engine::reality::kdf::transcript_hash(&refs);
        sched.derive_app(&th_ap);
        let want_c: [u8; 32] = [
            0x9e, 0x40, 0x64, 0x6c, 0xe7, 0x9a, 0x7f, 0x9d, 0xc0, 0x5a, 0xf8, 0x88, 0x9b, 0xce,
            0x65, 0x52, 0x87, 0x5a, 0xfa, 0x0b, 0x06, 0xdf, 0x00, 0x87, 0xf7, 0x92, 0xeb, 0xb7,
            0xc1, 0x75, 0x04, 0xa5,
        ];
        assert_eq!(sched.client_ap, want_c, "c ap traffic via derive_app");
    }

    #[test]
    fn rfc8448_derive_app_shape() {
        // derive_app с пустым дополнением не должен паниковать
        let ikm: [u8; 32] = [0x8b; 32];
        let th32: [u8; 32] = [
            0x86, 0x0c, 0x06, 0xed, 0xc0, 0x78, 0x58, 0xee, 0x8e, 0x78, 0xf0, 0xe7, 0x42, 0x8c,
            0x58, 0xed, 0xd6, 0xb4, 0x3f, 0x2c, 0xa3, 0xe6, 0xe9, 0x5f, 0x02, 0xed, 0x06, 0x3c,
            0xf0, 0xe1, 0xca, 0xd8,
        ];
        let mut sched = Schedule::new(&ikm, &th32);
        sched.derive_app(&th32);
        assert_eq!(sched.client_ap.len(), 32);
        assert_eq!(sched.server_ap.len(), 32);
    }
}
